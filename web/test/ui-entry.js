import { checkLang, checkAiPageStatus, checkPagePurpose, checkSummary, checkMachineOnlySpec, checkLanesForPersonSpec, checkKeysOnlyOnDecisions, checkPlanningContext, checkCalibrationReport, checkCorrection, checkMemoryEffect, checkRejectedAnswers, checkFullText, checkReview, checkDisagreement, checkProjectEntrances, checkTurnContext, checkBinaryPrediction, checkNavigation, checkLanding } from './ui-context.js';
import { checkPinned, checkAnswerMerge, checkWordingAgent, checkAnswerCardOnce, checkAnswerWordingBox, checkAnswerNothingToDo, checkWording, checkAnswerAdvances, checkAnswerFocus, checkAuditWordingWithoutWaiting, checkWordingLanding, checkAnswerKeys, checkWordingAskSends, checkWordingPlain } from './ui-answer.js';
import { checkNotebookTree, checkRulesPanel, checkKnowledgeFront, checkNotebookArticle, checkNotebook, checkClaimEvidence, checkHandoff, checkLessons, checkManageArticle, checkBackgroundArticleDraft, checkCompareArticle, checkComparisonReason } from './ui-knowledge.js';
import { checkAnswerNotRevertedByOldLoad, checkSwitchDuringAnswerKeepsLoad, checkAnswerCountOnlyForNewWaits, checkReloadDuringAnswerSend, checkFocusedLoading, checkLoadOrdering, checkLazyNavigation, checkDecisionContinuation } from './ui-loading.js';
import { checkUtilityConflicts, checkPhoneAnswerBar } from './ui-css.js';
import { checkAnswerTargetLifetime } from './ui-answer-recovery.js';


export async function run() {
  const target = document.getElementById('app');
  const continuationOK = await checkDecisionContinuation(target);
  const quietOK = checkAnswerNothingToDo(target);
  const answerTargetOK = await checkAnswerTargetLifetime(target);
  const backgroundDraftOK = await checkBackgroundArticleDraft(target);
  const manageArticleOK = await checkManageArticle(target);
  const compareArticleOK = await checkCompareArticle(target);
  const comparisonReasonOK = await checkComparisonReason(target);
  const knowledgeFrontOK = checkKnowledgeFront(target);
  const aiStatusOK = checkAiPageStatus(target);
  const purposeOK = await checkPagePurpose(target);
  const articleOK = await checkNotebookArticle(target);
  const planningOK = checkPlanningContext(target);
  const calibrationOK = checkCalibrationReport(target);
  const contextOK = checkTurnContext(target);
  const binaryOK = await checkBinaryPrediction(target);
  const navigationOK = await checkNavigation(target);
  const focusOK = checkAnswerFocus(target);
  const landingOK = await checkLanding(target);
  const evidenceOK = checkClaimEvidence(target);
  const loadingOK = await checkFocusedLoading(target);
  const orderingOK = await checkLoadOrdering();
  const lazyNavOK = await checkLazyNavigation(target);
  const summaryOK = await checkSummary(target);
  const keysOK = await checkKeysOnlyOnDecisions(target);
  const machineOnlyOK = await checkMachineOnlySpec(target);
  const treeOK = await checkNotebookTree(target);
  const lanesOK = await checkLanesForPersonSpec(target);
  const conflictsOK = await checkUtilityConflicts(target);
  const handoffOK = await checkHandoff(target);
  const lessonsOK = checkLessons(target);
  const reloadOK = await checkReloadDuringAnswerSend(target);
  const switchOK = await checkSwitchDuringAnswerKeepsLoad(target);
  const countOK = await checkAnswerCountOnlyForNewWaits(target);
  const rulesOK = await checkRulesPanel(target);
  const advanceOK = await checkAnswerAdvances(target);
  const revertOK = await checkAnswerNotRevertedByOldLoad(target);
  const onceOK = await checkAnswerCardOnce(target);
  const wordingBoxOK = await checkAnswerWordingBox(target);
  const auditOK = [await checkAuditWordingWithoutWaiting(target), await checkWordingLanding(target), await checkAnswerKeys(target), await checkWordingAskSends(target), checkPhoneAnswerBar(target), checkWordingPlain(target)].every(Boolean);
  const ok = comparisonReasonOK && compareArticleOK && backgroundDraftOK && manageArticleOK && auditOK && aiStatusOK && purposeOK && knowledgeFrontOK && onceOK && wordingBoxOK && quietOK && reloadOK && rulesOK && switchOK && countOK && advanceOK && revertOK && lessonsOK && handoffOK && conflictsOK && summaryOK && keysOK && machineOnlyOK && treeOK && lanesOK && planningOK && calibrationOK && loadingOK && orderingOK && lazyNavOK && evidenceOK && contextOK && binaryOK && navigationOK && focusOK && landingOK && checkLang(target) && checkPinned(target) && checkAnswerMerge(target) && await checkWording(target) && await checkWordingAgent(target) && await checkNotebook(target) && checkMemoryEffect(target) && checkRejectedAnswers(target) && checkCorrection(target) && await checkReview(target) && await checkDisagreement(target) && checkFullText(target) && await checkProjectEntrances(target);
  if (!continuationOK || !ok || !articleOK || !answerTargetOK) process.exit(1);
}
