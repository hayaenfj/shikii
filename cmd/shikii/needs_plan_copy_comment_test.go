package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// A copy the person commented is kept, also when the comment sits on the calibration key (the generated block is left out, not the comment).
func TestPersonCommentOnCalibrationKeySurvivesRefresh(t *testing.T) {
	legacy, current := refreshFixtureTexts(t)
	copied := append(append([]byte{}, legacy...), []byte("\n# my note: keep this comment\ncalibration:\n  method: platt\n")...)
	path := filepath.Join(t.TempDir(), "needs-plan.yaml")
	if err := os.WriteFile(path, copied, 0o600); err != nil {
		t.Fatal(err)
	}
	changed, err := refreshNeedsPlanCopy(path, current)
	if err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(path)
	if changed || !strings.Contains(string(after), "my note: keep this comment") {
		t.Fatalf("a copy with the person's comment must be kept: changed=%v comment_kept=%v", changed, strings.Contains(string(after), "my note: keep this comment"))
	}
}

// Control: the same comment outside the calibration pair keeps the copy.
func TestPersonCommentOutsideCalibrationKeepsCopy(t *testing.T) {
	legacy, current := refreshFixtureTexts(t)
	copied := append(append([]byte{}, legacy...), []byte("\n# my note: keep this comment\n")...)
	path := filepath.Join(t.TempDir(), "needs-plan.yaml")
	if err := os.WriteFile(path, copied, 0o600); err != nil {
		t.Fatal(err)
	}
	changed, err := refreshNeedsPlanCopy(path, current)
	if err != nil {
		t.Fatal(err)
	}
	if changed {
		t.Fatalf("control: a comment outside the calibration pair must keep the copy: changed=%v", changed)
	}
}

// Control: the generated comment on the calibration key alone does not make a copy the person's, so an earlier built-in copy that
// `calibrate --write` has calibrated is still refreshed.
func TestGeneratedCalibrationCommentStillRefreshes(t *testing.T) {
	legacy, current := refreshFixtureTexts(t)
	generated := "\n# The calibration block is generated by `shikii calibrate --write`. Do not write it by hand.\ncalibration:\n  method: platt\n"
	copied := append(append([]byte{}, legacy...), []byte(generated)...)
	path := filepath.Join(t.TempDir(), "needs-plan.yaml")
	if err := os.WriteFile(path, copied, 0o600); err != nil {
		t.Fatal(err)
	}
	changed, err := refreshNeedsPlanCopy(path, current)
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Fatal("control: an earlier built-in copy with only the generated calibration comment must be refreshed")
	}
}

// A person who edits the copy while it is being refreshed keeps that edit: the refresh checks the copy again just before it writes.
func TestRefreshKeepsAPersonEditMadeWhileRefreshing(t *testing.T) {
	legacy, current := refreshFixtureTexts(t)
	path := filepath.Join(t.TempDir(), "needs-plan.yaml")
	if err := os.WriteFile(path, legacy, 0o600); err != nil {
		t.Fatal(err)
	}
	edit := []byte(string(legacy) + "\n# edited by the person during the refresh\n")
	refreshBeforeWrite = func() {
		if err := os.WriteFile(path, edit, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	defer func() { refreshBeforeWrite = func() {} }()
	changed, err := refreshNeedsPlanCopy(path, current)
	if err != nil {
		t.Fatal(err)
	}
	after, _ := os.ReadFile(path)
	if changed || string(after) != string(edit) {
		t.Fatalf("the person's edit made during the refresh was overwritten: changed=%v after_has_edit=%v", changed, string(after) == string(edit))
	}
}

// refreshFixtureTexts returns the earliest built-in needs-plan text and the current one, as the seeding reads them.
func refreshFixtureTexts(t *testing.T) ([]byte, []byte) {
	t.Helper()
	legacy, err := legacySeedFS.ReadFile("legacy/needs-plan-0.34.0.yaml")
	if err != nil {
		t.Fatal(err)
	}
	current, err := os.ReadFile("../../integrations/claude-code/specs/needs-plan.yaml")
	if err != nil {
		t.Fatal(err)
	}
	return legacy, current
}
