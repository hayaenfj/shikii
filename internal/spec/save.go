// Save writes back to the path it was loaded from. It rewrites only the `calibration` key and
// keeps all other wording, comments and ordering as in the file (the calibration block is generated; the rest is written by people).
func (s *Spec) Save() error {
	if s.path == "" {
		return fmt.Errorf("spec has no path")
	}
	src, err := os.ReadFile(s.path)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return err
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return fmt.Errorf("%s: top level must be a mapping", s.path)
	}
	root := doc.Content[0]
	// Write back only the two generated parts (the calibration block and the candidates tune adds). Wording, comments and other fields are untouched.
	// Calibrations overlap (the CLI for one model, serve's automatic calibration for another model or the other rung): keep the lines
	// another process wrote between this copy's load and this save.
	calibration := mergeCalibration(s.loadedCalibration, onDiskCalibration(root), s.Calibration)
	if err := setMappingKey(root, "calibration", calibration, len(calibration) == 0, "The calibration block is generated by `shikii calibrate --write`. Do not write it by hand."); err != nil {
		return err
	}
	// Other processes add candidates too (the page's /v1/tune/variant, background tune --propose, calibrate --write). So as not to drop candidates added between reading and writing,
	// merge the candidates in the file with ours by name (ours wins on the same name). If untouched, do not re-encode (people's comments stay)
	merged := mergeVariants(onDiskVariants(root), s.Variants, s.hadVariants)
	if variantsChanged(root, merged) {
		if err := setMappingKey(root, "variants", merged, len(merged) == 0, "Candidate wordings. `shikii tune` scores them (--propose adds them). Not part of the key."); err != nil {
			return err
		}
		s.Variants = merged
		s.hadVariants = len(merged) > 0
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	// Write in the same folder, then rename (a crash midway does not break the original spec; serve rereads it every time)
	tmp, err := os.CreateTemp(filepath.Dir(s.path), filepath.Base(s.path)+".tmp-*")
	if err != nil {
		return err
	}
	if _, err := tmp.Write(buf.Bytes()); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := chmodSaved(tmp.Name(), 0o644); err != nil && !errors.Is(err, syscall.EPERM) { // Linux's exFAT and FAT refuse modes (0.9.10)
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Rename(tmp.Name(), s.path); err != nil {
		return err
	}
	s.Calibration = calibration
	s.loadedCalibration = copyCalibration(calibration)
	return nil
}

// onDiskCalibration returns the calibration lines in the file (nil if there are none or they cannot be read).
func onDiskCalibration(root *yaml.Node) []Calibration {
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "calibration" {
			var lines []Calibration
			if root.Content[i+1].Decode(&lines) != nil {
				return nil
			}
			return lines
		}
	}
	return nil
}

// mergeCalibration merges three lists by (model, spec hash): loaded is what this copy read, onDisk is the file now, mine is this copy now.
// A line this copy added or changed is ours. A line this copy never touched follows the file (another process may have replaced or
// removed it). A line this copy dropped stays dropped. A line another process added in the meantime is kept, after ours.
// When the file still holds what this copy read, the result is mine as it is.
func mergeCalibration(loaded, onDisk, mine []Calibration) []Calibration {
	if reflect.DeepEqual(copyCalibration(loaded), copyCalibration(onDisk)) {
		return mine
	}
	key := func(c Calibration) string { return c.Model + "\x00" + c.SpecHash }
	loadedBy, diskBy := map[string]Calibration{}, map[string]Calibration{}
	for _, c := range loaded {
		loadedBy[key(c)] = c
	}
	for _, c := range onDisk {
		diskBy[key(c)] = c
	}
	out := make([]Calibration, 0, len(mine)+len(onDisk))
	ours := map[string]bool{}
	for _, c := range mine {
		k := key(c)
		ours[k] = true
		if was, ok := loadedBy[k]; ok && reflect.DeepEqual(copyCalibration([]Calibration{was}), copyCalibration([]Calibration{c})) {
			if now, ok := diskBy[k]; ok {
				out = append(out, now)
			}
			continue
		}
		out = append(out, c)
	}
	for _, c := range onDisk {
		k := key(c)
		if _, had := loadedBy[k]; !ours[k] && !had {
			out = append(out, c)
		}
	}
	return out
}

// copyCalibration copies the lines as the file holds them: the per-option biases are copied, and the fields that are not written
// (Discrimination) are left out, so two copies compare equal exactly when they would be written the same.
func copyCalibration(in []Calibration) []Calibration {
	if len(in) == 0 {
		return nil
	}
	out := make([]Calibration, len(in))
	for i, c := range in {
		c.Discrimination = nil
		if len(c.Biases) == 0 {
			c.Biases = nil
		} else {
			biases := make(map[string]float64, len(c.Biases))
			for k, v := range c.Biases {
				biases[k] = v
			}
			c.Biases = biases
		}
		out[i] = c
	}
	return out
}

// chmodSaved sets the saved spec's mode; tests swap it to refuse like Linux's exFAT and FAT drivers.
var chmodSaved = os.Chmod

// setMappingKey replaces root's key with value (appends it if missing, removes it if empty).
// variantsChanged reports whether the variants in the file differ from the current value.
// onDiskVariants returns the variants in the file (nil if unreadable).
func onDiskVariants(root *yaml.Node) []Variant {
	variants, _, err := decodeOnDiskVariants(root)
	if err != nil {
		return nil
	}
	return variants
}

func decodeOnDiskVariants(root *yaml.Node) ([]Variant, bool, error) {
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "variants" {
			var variants []Variant
			err := root.Content[i+1].Decode(&variants)
			return variants, true, err
		}
	}
	return nil, false, nil
}

// mergeVariants merges the file's candidates (onDisk) with ours (mine) by name: file order first, then the ones only we have. mine wins on the same name.
// If mine is empty and this copy had candidates (hadVariants), the result is empty (a write that clears all candidates).
// A copy that never had any (calibrate --write loaded before a candidate was proposed) leaves the file's candidates as they are.
func mergeVariants(onDisk, mine []Variant, hadVariants bool) []Variant {
	if len(mine) == 0 && !hadVariants {
		return onDisk
	}
	if len(onDisk) == 0 || len(mine) == 0 { // if we emptied it, keep it empty (a write that clears candidates). If the file has none, keep ours
		return mine
	}
	byName := map[string]Variant{}
	for _, v := range mine {
		byName[v.Name] = v
	}
	out := make([]Variant, 0, len(onDisk)+len(mine))
	seen := map[string]bool{}
	for _, v := range onDisk {
		if m, ok := byName[v.Name]; ok {
			out = append(out, m)
		} else {
			out = append(out, v)
		}
		seen[v.Name] = true
	}
	for _, v := range mine {
		if !seen[v.Name] {
			out = append(out, v)
		}
	}
	return out
}

func variantsChanged(root *yaml.Node, now []Variant) bool {
	onDisk, present, err := decodeOnDiskVariants(root)
	if err != nil {
		return true
	}
	if !present {
		return len(now) > 0
	}
	return !reflect.DeepEqual(onDisk, now)
}

func setMappingKey(root *yaml.Node, key string, value any, empty bool, headComment string) error {
	at := -1
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == key {
			at = i
			break
		}
	}
	switch {
	case empty && at >= 0:
		root.Content = append(root.Content[:at], root.Content[at+2:]...)
	case empty:
	default:
		var val yaml.Node
		if err := val.Encode(value); err != nil {
			return err
		}
		if at >= 0 {
			root.Content[at+1] = &val
		} else {
			k := &yaml.Node{Kind: yaml.ScalarNode, Value: key, HeadComment: headComment}
			root.Content = append(root.Content, k, &val)
		}
	}
	return nil
}

// Path is where it was loaded from.
func (s *Spec) Path() string { return s.path }
