// Package spec reads and writes decision specs (Decision Spec).
// One decision = one YAML file. It keeps the model-independent part (question, state, thresholds)
// apart from the model-dependent part (calibration); calibration is keyed by (spec hash, model).
package spec

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"sort"
	"strings"
	"syscall"

	"github.com/hayaenfj/shikii/internal/calib"
	"gopkg.in/yaml.v3"
)

// Type is the question type. The three System One forms.
type Type string

const (
	Noul   Type = "noul"
	Choice Type = "choice"
	Score  Type = "score"
)

// Option is one choice in a choice question. A description is required (a bare label causes misrouting).
type Option struct {
	ID          string `yaml:"id"`
	Description string `yaml:"description"`
}

// State is how the text passed to the decision is built. Input missing a Required name is not decided.
type State struct {
	Template string   `yaml:"template"`
	Required []string `yaml:"required"`
	// Context is an optional layout that "adds context and asks again only when unsure". It uses every required input and adds one or more inputs not in template.
	// It is used only when the added inputs are present and the minimal question's answer is in the ask band. The context question has its own hash (ContextHash) and its own calibration.
	Context string `yaml:"context,omitempty"`
}

var placeholderRe = regexp.MustCompile(`\{\{\s*([A-Za-z0-9_]+)\s*\}\}`)

// placeholders returns the {{ name }} entries in template, in order of appearance (no duplicates).
func placeholders(tpl string) []string {
	var out []string
	seen := map[string]bool{}
	for _, m := range placeholderRe.FindAllStringSubmatch(tpl, -1) {
		if !seen[m[1]] {
			seen[m[1]] = true
			out = append(out, m[1])
		}
	}
	return out
}

// ContextInputs returns the inputs context adds (placeholders not in required), sorted by name. nil when there is no context.
func (s State) ContextInputs() []string {
	if s.Context == "" {
		return nil
	}
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	var out []string
	for _, p := range placeholders(s.Context) {
		if !req[p] {
			out = append(out, p)
		}
	}
	sort.Strings(out)
	return out
}

func (s State) validateContext() error {
	if s.Context == "" {
		return nil
	}
	for _, r := range s.Required {
		if !strings.Contains(s.Context, "{{ "+r+" }}") && !strings.Contains(s.Context, "{{"+r+"}}") {
			return fmt.Errorf("state.context: does not mention required input %q", r)
		}
	}
	if len(s.ContextInputs()) == 0 {
		return fmt.Errorf("state.context: must add at least one input that state.template does not use (it is the context asked for only when the minimal question is unsure)")
	}
	return nil
}

// Policy lists where text may be sent. In a tainted session hosted is removed automatically.
type Policy struct {
	SendTo []string `yaml:"send_to"` // "hosted" | "local"
	PII    *bool    `yaml:"pii"`     // true: the text can contain personal information (never sent to hosted). false: it cannot. No default (leaving it out is an error). This tool does not judge what counts as personal information
}

// Thresholds are named thresholds. Business code looks only at the band.
// Level is for score only: the band is decided by P(level ≥ Level) instead of "the probability of the top level".
// On an ordinal scale the probability splits across neighbouring levels, so looking only at the top level makes it look weaker than it is.
type Thresholds struct {
	Act   float64 `yaml:"act"`
	Ask   float64 `yaml:"ask"`
	Level int     `yaml:"level,omitempty"`
}

// Eval is where the labeled data lives and the minimum count needed for calibration.
type Eval struct {
	Labeled string `yaml:"labeled,omitempty"`
	MinN    int    `yaml:"min_n"`
}

// Calibration is generated by the calibrate command. Do not write it by hand.
// Only entries whose SpecHash and Model both match are used.
type Calibration struct {
	Model       string             `yaml:"model"`
	SpecHash    string             `yaml:"spec_hash"`
	Method      string             `yaml:"method"` // "platt"(noul) | "vector"(choice/score) | "identity"(verified, no constants)
	Bias        float64            `yaml:"bias,omitempty"`
	Temperature float64            `yaml:"temperature,omitempty"`
	Biases      map[string]float64 `yaml:"biases,omitempty"`           // vector: bias per option
	PrecisionAt float64            `yaml:"precision_at_act,omitempty"` // precision at the act threshold (after calibration)
	FittedOn    string             `yaml:"fitted_on,omitempty"`
	N           int                `yaml:"n"`
	NHuman      int                `yaml:"n_human,omitempty"` // how many of them are truths decided by a person (or by the outcome). Written back only when this is at least min_n
	Brier       float64            `yaml:"brier"`
	ECE         float64            `yaml:"ece"`
	FittedAt    string             `yaml:"fitted_at"`
	// Discrimination is how well the probabilities ranked the truths in this calibration (calibrate fills it for its report and for
	// stopping a question that cannot be answered; it is not written to the spec, 0.10)
	Discrimination *calib.Discrimination `yaml:"-"`
}

// Spec is the spec of one decision.
type Spec struct {
	ID          string        `yaml:"id"`
	Version     int           `yaml:"version"`
	Type        Type          `yaml:"type"`
	Question    string        `yaml:"question"`
	Options     []Option      `yaml:"options,omitempty"` // choice
	Levels      []string      `yaml:"levels,omitempty"`  // score (lowest first)
	State       State         `yaml:"state"`
	Policy      Policy        `yaml:"policy"`
	Thresholds  Thresholds    `yaml:"thresholds"`
	Eval        Eval          `yaml:"eval"`
	Calibration []Calibration `yaml:"calibration,omitempty"`
	// Display holds translations for the screen (language code → title, options, levels). Never sent to the model and not part of the calibration key.
	Display map[string]Display `yaml:"display,omitempty"`
	// Variants are candidate wordings (`shikii tune` scores them against the saved truths). Not part of the key. An adopted one becomes a new version in a separate file.
	Variants []Variant `yaml:"variants,omitempty"`
	Steps    []Step    `yaml:"steps,omitempty"` // breakdown of a choice: a list of yes/no questions. When present, all steps are asked in one call instead of one multi-choice question, and the distribution is the product along the branches
	// Layout is the prompt arrangement (state-last | state-first | plain; empty means the backend's default). It is part of the wording, so it goes into the hash.
	// shikii-readout follows it and the arrangement is appended to the model name in the response, so the calibration key splits too. Decision models ignore it.
	Layout string `yaml:"layout,omitempty"`

	path string
}

// Layouts are the arrangement names shikii knows. They match shikii-readout's orderings.
var Layouts = []string{"state-last", "state-first", "plain"}

func validateLayout(l string) error {
	if l == "" {
		return nil
	}
	for _, k := range Layouts {
		if l == k {
			return nil
		}
	}
	return fmt.Errorf("layout: unknown %q (one of %s)", l, strings.Join(Layouts, " | "))
}

// Variant is a candidate wording. It overrides only the fields it sets (missing fields keep the current spec).
type Variant struct {
	Name     string            `yaml:"name"`
	Question string            `yaml:"question,omitempty"`
	Options  map[string]string `yaml:"options,omitempty"`  // choice: id → reworded description
	Levels   []string          `yaml:"levels,omitempty"`   // score: reworded levels (same count)
	Template string            `yaml:"template,omitempty"` // how state is arranged
	Steps    []Step            `yaml:"steps,omitempty"`    // choice: break the multi-choice into a list of yes/no questions (empty keeps the current one)
	Layout   string            `yaml:"layout,omitempty"`   // prompt arrangement (state-last | state-first | plain). Empty keeps the current one
}

// Step is one step of a breakdown: a yes/no question and which option each answer settles on.
// A middle step settles on only one of yes or no (the other goes to the next step); the last step settles on both.
// Each option appears in exactly one leaf. The breakdown is part of the wording, so it goes into the key (hash).
type Step struct {
	Ask string `yaml:"ask"`
	Yes string `yaml:"yes,omitempty"`
	No  string `yaml:"no,omitempty"`
}

// validateSteps checks the shape of the breakdown.
func validateSteps(typ Type, options []Option, steps []Step) error {
	if len(steps) == 0 {
		return nil
	}
	if typ != Choice {
		return fmt.Errorf("steps: only a choice question can be decomposed into yes/no steps")
	}
	known := map[string]bool{}
	for _, o := range options {
		known[o.ID] = true
	}
	seen := map[string]int{}
	leaf := func(i int, id string) error {
		if !known[id] {
			return fmt.Errorf("steps[%d]: %q is not an option of this spec", i, id)
		}
		seen[id]++
		return nil
	}
	for i, st := range steps {
		if strings.TrimSpace(st.Ask) == "" {
			return fmt.Errorf("steps[%d]: ask is required", i)
		}
		last := i == len(steps)-1
		switch {
		case st.Yes != "" && st.No != "":
			if !last {
				return fmt.Errorf("steps[%d]: only the last step may settle both yes and no; a middle step settles one and passes the other on", i)
			}
		case st.Yes == "" && st.No == "":
			return fmt.Errorf("steps[%d]: a step must settle yes, no or (last step) both", i)
		case last:
			return fmt.Errorf("steps[%d]: the last step must settle both yes and no", i)
		}
		for _, id := range []string{st.Yes, st.No} {
			if id != "" {
				if err := leaf(i, id); err != nil {
					return err
				}
			}
		}
	}
	for _, o := range options {
		if seen[o.ID] != 1 {
			return fmt.Errorf("steps: option %q must appear exactly once as a leaf, appears %d times", o.ID, seen[o.ID])
		}
	}
	return nil
}

func copySteps(in []Step) []Step {
	if len(in) == 0 {
		return nil
	}
	return append([]Step(nil), in...)
}

// WithVariant returns a copy with the candidate applied (no path; the key changes).
func (s *Spec) WithVariant(v Variant) *Spec {
	c := *s
	c.Calibration = nil
	c.Variants = nil
	c.path = ""
	if v.Question != "" {
		c.Question = v.Question
	}
	if v.Template != "" {
		c.State = State{Template: v.Template, Required: append([]string(nil), s.State.Required...), Context: s.State.Context}
	}
	if len(v.Options) > 0 {
		c.Options = make([]Option, len(s.Options))
		for i, o := range s.Options {
			if d, ok := v.Options[o.ID]; ok {
				o.Description = d
			}
			c.Options[i] = o
		}
	}
	if len(v.Levels) > 0 {
		c.Levels = append([]string(nil), v.Levels...)
	}
	if len(v.Steps) > 0 {
		c.Steps = copySteps(v.Steps)
	} else {
		c.Steps = copySteps(s.Steps)
	}
	if v.Layout != "" {
		c.Layout = v.Layout
	}
	return &c
}

// Display is the screen translation for one language. Options maps a choice id (yes / no for noul) → display name; Levels holds the score levels (lowest first, same count as levels).
type Display struct {
	Title    string            `yaml:"title,omitempty"`
	Question string            `yaml:"question,omitempty"`
	Options  map[string]string `yaml:"options,omitempty"`
	Levels   []string          `yaml:"levels,omitempty"`
}

// Load reads the YAML and validates it.
func Load(path string) (*Spec, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var s Spec
	if err := yaml.Unmarshal(b, &s); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	s.path = path
	if err := s.Validate(); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &s, nil
}

// Validate checks that the spec is consistent.
func (s *Spec) Validate() error {
	if s.ID == "" {
		return fmt.Errorf("id is required")
	}
	if strings.TrimSpace(s.Question) == "" {
		return fmt.Errorf("question is required")
	}
	switch s.Type {
	case Noul:
	case Choice:
		if len(s.Options) < 2 {
			return fmt.Errorf("choice needs at least 2 options")
		}
		for _, o := range s.Options {
			if o.ID == "" || strings.TrimSpace(o.Description) == "" {
				return fmt.Errorf("choice option %q needs id and description", o.ID)
			}
		}
	case Score:
		if len(s.Levels) < 2 || len(s.Levels) > 10 {
			return fmt.Errorf("score needs 2..10 levels, got %d", len(s.Levels))
		}
	default:
		return fmt.Errorf("unknown type %q", s.Type)
	}
	if err := validateSteps(s.Type, s.Options, s.Steps); err != nil {
		return err
	}
	if err := validateLayout(s.Layout); err != nil {
		return err
	}
	if strings.TrimSpace(s.State.Template) == "" {
		return fmt.Errorf("state.template is required")
	}
	if err := s.State.validateContext(); err != nil {
		return err
	}
	if len(s.Policy.SendTo) == 0 {
		return fmt.Errorf("policy.send_to is required")
	}
	for _, d := range s.Policy.SendTo {
		if d != "hosted" && d != "local" {
			return fmt.Errorf("policy.send_to: unknown destination %q", d)
		}
	}
	if s.Eval.MinN < 1 {
		return fmt.Errorf("eval.min_n must be at least 1 (how many truths before a calibration may be written; 50 is a sensible start)")
	}
	if s.Policy.PII == nil {
		return fmt.Errorf("policy.pii is required: true (the text can contain personal information: never sent to a hosted endpoint) or false (it cannot). shikii does not decide what counts as personal information; you do")
	}
	if !(0 < s.Thresholds.Ask && s.Thresholds.Ask <= s.Thresholds.Act && s.Thresholds.Act <= 1) {
		return fmt.Errorf("thresholds must satisfy 0 < ask <= act <= 1")
	}
	if s.Thresholds.Level != 0 {
		if s.Type != Score {
			return fmt.Errorf("thresholds.level is only for score")
		}
		if s.Thresholds.Level < 1 || s.Thresholds.Level > len(s.Levels)-1 {
			return fmt.Errorf("thresholds.level must be in 1..%d", len(s.Levels)-1)
		}
	}
	for lang, d := range s.Display {
		for id := range d.Options {
			if !s.hasTruthID(id) {
				return fmt.Errorf("display.%s.options: %q is not an option of this spec", lang, id)
			}
		}
		if len(d.Levels) > 0 && len(d.Levels) != len(s.Levels) {
			return fmt.Errorf("display.%s.levels: %d entries, spec has %d levels", lang, len(d.Levels), len(s.Levels))
		}
	}
	names := map[string]bool{}
	for i, v := range s.Variants {
		if strings.TrimSpace(v.Name) == "" || names[v.Name] || v.Name == "current" {
			return fmt.Errorf("variants[%d]: name must be unique, non-empty and not \"current\"", i)
		}
		names[v.Name] = true
		if v.Question == "" && len(v.Options) == 0 && len(v.Levels) == 0 && v.Template == "" && len(v.Steps) == 0 && v.Layout == "" {
			return fmt.Errorf("variants[%d] (%s): changes nothing", i, v.Name)
		}
		if err := validateSteps(s.Type, s.Options, v.Steps); err != nil {
			return fmt.Errorf("variants[%d] (%s).%w", i, v.Name, err)
		}
		if err := validateLayout(v.Layout); err != nil {
			return fmt.Errorf("variants[%d] (%s).%w", i, v.Name, err)
		}
		for id := range v.Options {
			if s.Type != Choice || !s.hasTruthID(id) {
				return fmt.Errorf("variants[%d] (%s).options: %q is not an option of this spec", i, v.Name, id)
			}
		}
		if len(v.Levels) > 0 && len(v.Levels) != len(s.Levels) {
			return fmt.Errorf("variants[%d] (%s).levels: %d entries, spec has %d levels", i, v.Name, len(v.Levels), len(s.Levels))
		}
		if v.Template != "" {
			for _, r := range s.State.Required {
				if !strings.Contains(v.Template, "{{ "+r+" }}") && !strings.Contains(v.Template, "{{"+r+"}}") {
					return fmt.Errorf("variants[%d] (%s).template: does not mention required input %q", i, v.Name, r)
				}
			}
		}
		// The name goes into wiki/runs file names and tables: separators, spaces and overly long names are rejected
		if v.Name == "" || len(v.Name) > 60 || strings.ContainsAny(v.Name, "/\\ \t\r\n") || strings.Contains(v.Name, "..") {
			return fmt.Errorf("variants[%d].name %q: 1 to 60 characters, no spaces, slashes or \"..\" (it becomes part of a file name)", i, v.Name)
		}
	}
	return nil
}

// hasTruthID reports whether an id a screen translation points to exists in the spec (option id for choice, yes / no for noul).
// PIISensitive reports whether the text is declared as possibly holding personal information (never sent to hosted).
func (s *Spec) PIISensitive() bool { return s.Policy.PII != nil && *s.Policy.PII }

func (s *Spec) hasTruthID(id string) bool {
	switch s.Type {
	case Noul:
		return id == "yes" || id == "no"
	case Choice:
		for _, o := range s.Options {
			if o.ID == id {
				return true
			}
		}
	}
	return false
}

// TruthKeys returns every raw key (yes/no for noul, option ids for choice, level numbers for score).
func (s *Spec) TruthKeys() []string {
	switch s.Type {
	case Noul:
		return []string{"yes", "no"}
	case Score:
		out := make([]string, len(s.Levels))
		for i := range s.Levels {
			out[i] = fmt.Sprint(i)
		}
		return out
	}
	out := make([]string, len(s.Options))
	for i, o := range s.Options {
		out[i] = o.ID
	}
	return out
}

// HasTruthKey reports whether id is a valid raw key: yes/no for noul, an option id for choice, a level number ("0".."n-1") for score.
func (s *Spec) HasTruthKey(id string) bool {
	if s.Type == Score {
		for i := range s.Levels {
			if id == fmt.Sprint(i) {
				return true
			}
		}
		return false
	}
	return s.hasTruthID(id)
}

// Hash is the hash that keys calibration. It is built from the question, type, state template, options and levels.
// Thresholds and policy are left out (changing them keeps the calibration valid).
func (s *Spec) Hash() string {
	h := sha256.New()
	w := func(parts ...string) {
		for _, p := range parts {
			h.Write([]byte(p))
			h.Write([]byte{0})
		}
	}
	// thresholds.level decides the band and is not part of the calibration key (same as the thresholds)
	w(string(s.Type), s.Question, s.State.Template)
	for _, o := range s.Options {
		w(o.ID, o.Description)
	}
	for _, l := range s.Levels {
		w(l)
	}
	for _, st := range s.Steps { // the breakdown is part of the wording. Specs without one keep their key
		w("step", st.Ask, st.Yes, st.No)
	}
	if s.Layout != "" { // the arrangement is part of the wording too. Specs without one keep their key
		w("layout", s.Layout)
	}
	return hex.EncodeToString(h.Sum(nil))[:16]
}

// Render fills the template with the inputs. It returns the names of missing required inputs.
func (s *Spec) Render(inputs map[string]string) (state string, missing []string) {
	for _, r := range s.State.Required {
		if strings.TrimSpace(inputs[r]) == "" {
			missing = append(missing, r)
		}
	}
	sort.Strings(missing)
	if len(missing) > 0 {
		return "", missing
	}
	state = s.State.Template
	for k, v := range inputs {
		state = strings.ReplaceAll(state, "{{ "+k+" }}", v)
		state = strings.ReplaceAll(state, "{{"+k+"}}", v)
	}
	return state, nil
}

// CalibrationFor returns the calibration matching the current hash and model, or nil.
func (s *Spec) CalibrationFor(model string) *Calibration {
	h := s.Hash()
	for i := range s.Calibration {
		c := &s.Calibration[i]
		if c.Model == model && c.SpecHash == h {
			return c
		}
	}
	return nil
}

// PutCalibration replaces the calibration with the same (hash, model), or appends it.
func (s *Spec) PutCalibration(c Calibration) {
	// The same model keeps one line per step (the minimal question and, if any, the context step). Lines for old hashes (from before the wording changed) are replaced. Lines for other models are kept.
	kept := make([]Calibration, 0, len(s.Calibration)+1) // the copy (ContextSpec) shares the slice, so do not rewrite it in place
	for _, cur := range s.Calibration {
		if cur.Model != c.Model || (cur.SpecHash != c.SpecHash && s.LiveHash(cur.SpecHash)) {
			kept = append(kept, cur)
		}
	}
	s.Calibration = append(kept, c)
}

// HasContext reports whether there is a step that "adds context only when unsure".
func (s *Spec) HasContext() bool { return s.State.Context != "" }

// ContextSpec is the context question itself: a copy with template replaced by context and the added inputs made required.
// Its hash (Hash) differs, so its calibration is looked up separately. The calibration list and the file location are shared. nil when there is no context.
func (s *Spec) ContextSpec() *Spec {
	if !s.HasContext() {
		return nil
	}
	c := *s
	c.State = State{Template: s.State.Context, Required: append(append([]string(nil), s.State.Required...), s.State.ContextInputs()...)}
	c.Variants = nil
	c.Steps = copySteps(s.Steps)
	return &c
}

// ContextHash is the hash of the context step. Empty when there is none.
func (s *Spec) ContextHash() string {
	if c := s.ContextSpec(); c != nil {
		return c.Hash()
	}
	return ""
}

// LiveHash reports whether h is the hash of either step of the current wording (anything else is an old hash from before the wording changed).
func (s *Spec) LiveHash(h string) bool {
	return h == s.Hash() || (s.HasContext() && h == s.ContextHash())
}

// WithoutContext returns a copy that asks only the minimal question (same hash). Use it to measure without moving up a step, as in tune scoring or re-asking.
func (s *Spec) WithoutContext() *Spec {
	c := *s
	c.State.Context = ""
	return &c
}

// StateInputs returns only the inputs this spec's template uses (required and the template placeholders).
// The input hash is taken over these: even if the context inputs differ, the minimal question sees the same input.
func (s *Spec) StateInputs(in map[string]string) map[string]string {
	used := map[string]bool{}
	for _, r := range s.State.Required {
		used[r] = true
	}
	for _, p := range placeholders(s.State.Template) {
		used[p] = true
	}
	out := make(map[string]string, len(used))
	for k, v := range in {
		if used[k] {
			out[k] = v
		}
	}
	return out
}

// Save writes back to the path it was loaded from. It rewrites only the `calibration` key and
// keeps all other wording, comments and ordering as in the file (the calibration block is generated; the rest is written by people).
func (s *Spec) Save() error {
	if s.path == "" {
		return fmt.Errorf("spec has no path")
	}
	src, err := os.ReadFile(s.path)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return err
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return fmt.Errorf("%s: top level must be a mapping", s.path)
	}
	root := doc.Content[0]
	// Write back only the two generated parts (the calibration block and the candidates tune adds). Wording, comments and other fields are untouched.
	if err := setMappingKey(root, "calibration", s.Calibration, len(s.Calibration) == 0, "The calibration block is generated by `shikii calibrate --write`. Do not write it by hand."); err != nil {
		return err
	}
	// Other processes add candidates too (the page's /v1/tune/variant, background tune --propose, calibrate --write). So as not to drop candidates added between reading and writing,
	// merge the candidates in the file with ours by name (ours wins on the same name). If untouched, do not re-encode (people's comments stay)
	merged := mergeVariants(onDiskVariants(root), s.Variants)
	if variantsChanged(root, merged) {
		if err := setMappingKey(root, "variants", merged, len(merged) == 0, "Candidate wordings. `shikii tune` scores them (--propose adds them). Not part of the key."); err != nil {
			return err
		}
		s.Variants = merged
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	// Write in the same folder, then rename (a crash midway does not break the original spec; serve rereads it every time)
	tmp, err := os.CreateTemp(filepath.Dir(s.path), filepath.Base(s.path)+".tmp-*")
	if err != nil {
		return err
	}
	if _, err := tmp.Write(buf.Bytes()); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := chmodSaved(tmp.Name(), 0o644); err != nil && !errors.Is(err, syscall.EPERM) { // Linux's exFAT and FAT refuse modes (0.9.10)
		os.Remove(tmp.Name())
		return err
	}
	return os.Rename(tmp.Name(), s.path)
}

// chmodSaved sets the saved spec's mode; tests swap it to refuse like Linux's exFAT and FAT drivers.
var chmodSaved = os.Chmod

// setMappingKey replaces root's key with value (appends it if missing, removes it if empty).
// variantsChanged reports whether the variants in the file differ from the current value.
// onDiskVariants returns the variants in the file (nil if unreadable).
func onDiskVariants(root *yaml.Node) []Variant {
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "variants" {
			var onDisk []Variant
			if err := root.Content[i+1].Decode(&onDisk); err != nil {
				return nil
			}
			return onDisk
		}
	}
	return nil
}

// mergeVariants merges the file's candidates (onDisk) with ours (mine) by name: file order first, then the ones only we have. mine wins on the same name.
// If mine is empty, the result is empty (a write that clears all candidates).
func mergeVariants(onDisk, mine []Variant) []Variant {
	if len(onDisk) == 0 || len(mine) == 0 { // if we emptied it, keep it empty (a write that clears candidates). If the file has none, keep ours
		return mine
	}
	byName := map[string]Variant{}
	for _, v := range mine {
		byName[v.Name] = v
	}
	out := make([]Variant, 0, len(onDisk)+len(mine))
	seen := map[string]bool{}
	for _, v := range onDisk {
		if m, ok := byName[v.Name]; ok {
			out = append(out, m)
		} else {
			out = append(out, v)
		}
		seen[v.Name] = true
	}
	for _, v := range mine {
		if !seen[v.Name] {
			out = append(out, v)
		}
	}
	return out
}

func variantsChanged(root *yaml.Node, now []Variant) bool {
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == "variants" {
			var onDisk []Variant
			if err := root.Content[i+1].Decode(&onDisk); err != nil {
				return true
			}
			return !reflect.DeepEqual(onDisk, now)
		}
	}
	return len(now) > 0
}

func setMappingKey(root *yaml.Node, key string, value any, empty bool, headComment string) error {
	at := -1
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == key {
			at = i
			break
		}
	}
	switch {
	case empty && at >= 0:
		root.Content = append(root.Content[:at], root.Content[at+2:]...)
	case empty:
	default:
		var val yaml.Node
		if err := val.Encode(value); err != nil {
			return err
		}
		if at >= 0 {
			root.Content[at+1] = &val
		} else {
			k := &yaml.Node{Kind: yaml.ScalarNode, Value: key, HeadComment: headComment}
			root.Content = append(root.Content, k, &val)
		}
	}
	return nil
}

